// ── WhatsApp client ──────────────────────────────────────────────────────────
const client = new Client({
  authStrategy: new LocalAuth({ dataPath: '.wwebjs_auth' }),
  puppeteer: {
    headless: true,
    args: [
      '--no-sandbox',
      '--disable-setuid-sandbox',
      '--disable-dev-shm-usage',
      '--disable-accelerated-2d-canvas',
      '--no-first-run',
      '--no-zygote',
      '--disable-gpu',
    ],
  },
});

client.on('qr', (qr) => {
  currentQR = qr;
  isReady = false;
  console.log('[Jarvis WA] QR ready — open the service URL to scan.');
  qrcodeTerminal.generate(qr, { small: true });
});

client.on('authenticated', () => {
  console.log('[Jarvis WA] Authenticated — session saved.');
  currentQR = null;
});

client.on('auth_failure', (msg) => {
  console.error('[Jarvis WA] Auth failure:', msg);
  currentQR = null;
});

client.on('ready', () => {
  isReady = true;
  currentQR = null;
  console.log('[Jarvis WA] Bot ready and listening.');
});

client.on('disconnected', (reason) => {
  isReady = false;
  console.warn('[Jarvis WA] Disconnected:', reason);
});

client.on('message', async (msg) => {
  if (msg.fromMe) return;

  const chat = await msg.getChat();
  if (chat.isGroup) return;

  const text = (msg.body || '').trim();
  if (!text) return;

  const from = msg.from.replace('@c.us', '');
  console.log(`[Jarvis WA] ${from}: ${text.substring(0, 100)}`);

  if (!waEnabled) {
    console.log('[Jarvis WA] Skipped (disabled).');
    return;
  }

  const history = getHistory(from);
  const state = getState(from);

  history.push({ role: 'user', content: text });
  if (history.length > MAX_HISTORY) history.splice(0, history.length - MAX_HISTORY);

  const availCtx = await buildAvailContext(state, text);

  try {
    const response = await anthropic.messages.create({
      model: 'claude-haiku-4-5-20251001',
      max_tokens: 400,
      system: SYSTEM_PROMPT + stateContext(state) + availCtx,
      messages: history,
    });
    const reply = response.content[0]?.text?.trim();
    if (reply) {
      history.push({ role: 'assistant', content: reply });
      await msg.reply(reply);
      console.log(`[Jarvis WA] → ${reply.substring(0, 80)}`);

      extractState(history, state).then(newState => {
        Object.assign(state, newState);
        if (state.confirmed && state.breed && state.service && state.date && state.time && state.ownerName && state.petName) {
          postBooking(state, from);
          conversations.delete(from);
          bookingStates.delete(from);
          console.log(`[Jarvis WA] Booking submitted for ${from}`);
        }
      }).catch(e => console.error('[Jarvis WA] state update error:', e.message));
    }
  } catch (err) {
    console.error('[Jarvis WA] Anthropic error:', err.message);
  }
});

client.initialize();
